    const { card, container, refresh } = editor();
    card._draftDayLayoutKey = key; refresh();
    const active = [...container.querySelectorAll<HTMLButtonElement>(".day-tab.active")];
    expect(active).toHaveLength(key === "all" ? 7 : 5);
