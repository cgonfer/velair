const tag = "test-day-layout-editor";
if (!customElements.get(tag)) customElements.define(tag, VelairCard);
function editor(mixed = false) {
  const card = document.createElement(tag) as any;
  const blocks = [{ start: "08:00", action: "set_temperature", temperature: 21, hvac_mode: "heat" }];
  const zone = { enabled: true, day_layout_key: "weekdays_weekend", schedule: Object.fromEntries(WEEKDAYS.map((day) => [day, mixed && day === "tuesday" ? [] : structuredClone(blocks)])) };
  card._data = { active_overrides: {}, global: { mode: "auto" }, next_event: null, next_events: [], operational_status: "running", temperature_migration: { required: false }, home_assistant_temperature_unit: "°C", zones: { "climate.office": zone }, configured_entities: ["climate.office"], settings: { first_weekday: "monday", zone_order: [] }, configuration_revision: 4, temperature_unit: "°C" };
  card._selectedEntity = "climate.office"; card._selectedWeekday = "monday";
  card._resetDraftBlocks();
  const container = document.createElement("div");
  const refresh = () => render(renderScheduleEditor(card, "climate.office", card._data.zones["climate.office"]), container);
  refresh(); return { card, zone, container, refresh };
}
